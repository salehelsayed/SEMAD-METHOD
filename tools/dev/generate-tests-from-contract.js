#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { loadStoryContract } = require('../../semad-core/utils/story-contract');

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a) continue;
    if (a.startsWith('--')) {
      const key = a.replace(/^--/, '');
      const next = argv[i + 1];
      if (next && !next.startsWith('--')) { out[key] = next; i++; }
      else { out[key] = true; }
    } else { out._.push(a); }
  }
  return out;
}

function readFrontmatter(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return null;
  return yaml.load(m[1]);
}

function ensureDir(p) { fs.mkdirSync(p, { recursive: true }); }

function writeIfMissing(filePath, content) {
  if (fs.existsSync(filePath)) return false;
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function toTestSkeleton(storyId, item, filePath) {
  const ac = item.ac_id || 'AC-UNKNOWN';
  const title = (item.title || '').replace(/`/g, '');
  const rationale = item.rationale ? `// Rationale: ${item.rationale}\n` : '';
  const endpoint = item.endpoint_ref ? `${item.endpoint_ref.method || 'METHOD'} ${item.endpoint_ref.path || '/path'}` : '';
  return `/**
 * Story ${storyId} – ${ac}: ${title}
 * Autogenerated test skeleton from StoryContract.acceptanceTestMatrix
 */
${rationale}
describe('${storyId} – ${ac}', () => {
  test('${title || 'spec'} ${endpoint ? '(' + endpoint + ')' : ''}', async () => {
    // TODO: Implement test. Replace placeholder assertion.
    // Suggested Assertions: ${Array.isArray(item.assertions) ? JSON.stringify(item.assertions) : '[]'}
    expect(false).toBe(true);
  });
});
`;
}

function extractACsFromMarkdown(filePath) {
  try {
    const text = fs.readFileSync(filePath, 'utf8');
    const idx = text.indexOf('\n## Acceptance Criteria');
    if (idx === -1) return [];
    const cut = text.slice(idx + 1);
    const nextHeader = cut.search(/\n##\s+/);
    const section = nextHeader !== -1 ? cut.slice(0, nextHeader) : cut;
    const lines = section.split('\n').map(s => s.trim()).filter(Boolean);
    const bullets = lines.filter(l => /^(-|\d+\.|\*)\s+/.test(l));
    return bullets.map((b, i) => ({ id: `AC-${i + 1}`, title: b.replace(/^(-|\d+\.|\*)\s+/, '').trim() }));
  } catch (_) { return []; }
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const story = args.story || args._[0];
  if (!story) {
    console.error('Usage: generate-tests-from-contract --story <path-to-story.md>');
    process.exit(2);
  }
  const projectRoot = process.cwd();
  const storyPath = path.isAbsolute(story) ? story : path.join(projectRoot, story);
  if (!fs.existsSync(storyPath)) {
    console.error('Story not found:', storyPath);
    process.exit(2);
  }

  let sc;
  try {
    sc = loadStoryContract(storyPath).contract;
  } catch (e) {
    const fm = readFrontmatter(storyPath);
    if (!fm || !fm.StoryContract) {
      console.error('No StoryContract found (XML pointer or YAML)');
      process.exit(3);
    }
    sc = fm.StoryContract;
  }
  const storyId = sc.story_id || sc?.story?.storyId || path.basename(storyPath).replace(/\.md$/, '');
  const matrix = sc.acceptanceTestMatrix || {};
  const items = Array.isArray(matrix.items) ? matrix.items : [];
  let workItems = items.slice();
  if (workItems.length === 0) {
    // Fallback: derive from acceptanceCriteriaLinks or markdown AC section
    const links = Array.isArray(sc.acceptanceCriteriaLinks) ? sc.acceptanceCriteriaLinks : [];
    const derived = links.map((s, i) => {
      const m = String(s).match(/^([^:]+):\s*(.*)$/);
      const acId = m ? m[1].trim() : `AC-${i + 1}`;
      const title = m ? m[2].trim() : String(s).trim();
      return {
        ac_id: acId,
        title,
        test_files: [ { path: `tests/acceptance/${storyId}/${acId}.test.js`, framework: 'jest' } ],
        assertions: []
      };
    });
    if (derived.length === 0) {
      const mdAcs = extractACsFromMarkdown(storyPath);
      workItems = mdAcs.map(a => ({
        ac_id: a.id,
        title: a.title,
        test_files: [ { path: `tests/acceptance/${storyId}/${a.id}.test.js`, framework: 'jest' } ],
        assertions: []
      }));
    } else {
      workItems = derived;
    }
  }

  let created = 0;
  let existed = 0;
  const createdFiles = [];
  const existingFiles = [];

  for (const item of workItems) {
    const tfs = Array.isArray(item.test_files) ? item.test_files : [];
    for (const tf of tfs) {
      const p = tf && tf.path ? tf.path : null;
      if (!p) continue;
      const abs = path.isAbsolute(p) ? p : path.join(projectRoot, p);
      const skeleton = toTestSkeleton(storyId, item, abs);
      if (writeIfMissing(abs, skeleton)) {
        created++;
        createdFiles.push(path.relative(projectRoot, abs));
      } else {
        existed++;
        existingFiles.push(path.relative(projectRoot, abs));
      }
    }
  }

  console.log(JSON.stringify({ created, existed, createdFiles, existingFiles }));
  process.exit(0);
}

main();
